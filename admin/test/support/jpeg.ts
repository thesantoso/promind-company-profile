/** JPEG minimal yang valid secara struktur (SOI, APP0, SOF0 dengan dimensi, EOI), cukup untuk uji validasi. */
export function makeJpeg(width: number, height: number, padTo = 0): Uint8Array {
  const parts = [
    [0xff, 0xd8],
    [0xff, 0xe0, 0x00, 0x10, 0x4a, 0x46, 0x49, 0x46, 0x00, 0x01, 0x01, 0x00, 0x00, 0x01, 0x00, 0x01, 0x00, 0x00],
    [0xff, 0xc0, 0x00, 0x11, 0x08, height >> 8, height & 255, width >> 8, width & 255, 0x03, 0x01, 0x22, 0x00, 0x02, 0x11, 0x01, 0x03, 0x11, 0x01],
    [0xff, 0xd9],
  ].flat();
  const out = new Uint8Array(Math.max(parts.length, padTo));
  out.set(parts);
  return out;
}
